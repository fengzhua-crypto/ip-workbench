def _pick(title: str) -> str:
    if any(k in title for k in ("焦虑", "努力", "成长", "学")):
        return "成长"
    if any(k in title for k in ("驼背", "身体", "久坐", "健康", "动作")):
        return "身体"
    if any(k in title for k in ("存钱", "月薪", "账", "钱")):
        return "理财"
    if any(k in title for k in ("孩子", "作业", "育儿", "家长")):
        return "育儿"
    if any(k in title for k in ("精力", "效率", "清单", "时间")):
        return "效率"
    if any(k in title for k in ("认知", "学习", "知识")):
        return "认知"
    return random.choice(list(ARCHETYPES.keys()))


